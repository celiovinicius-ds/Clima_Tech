with open(JSON_PATH, "r", encoding="utf-8") as f:
    municipios = json.load(f)

atualizados = 0
for m in municipios:
    n_mun = norm(m["nome"])
    alt_encontrada = None
    if n_mun in ALTITUDES_GO:
        alt_encontrada = ALTITUDES_GO[n_mun]
    else:
        for k, v in ALTITUDES_GO.items():
            if norm(k) == n_mun or (len(n_mun) >= 5 and n_mun in norm(k)):
                alt_encontrada = v
                break
    
    if alt_encontrada is not None:
        m["altitude"] = float(alt_encontrada)
        atualizados += 1
    else:
        m["altitude"] = float(m.get("altitude") or 650.0)

with open(JSON_PATH, "w", encoding="utf-8") as f:
    json.dump(municipios, f, ensure_ascii=False, indent=2)

print(f"[SUCESSO] {atualizados} municípios de Goiás atualizados com suas altitudes oficiais em {JSON_PATH}!")